"""Modal launcher for the M2D Stage-1 arm fits.

Four spawned jobs, one per declared Stage-1 cell. Each fits BOTH arms -- A1 and
A3-MINIMAL -- at seed 0, re-scores M2B's native S4 checkpoint on the same panel
without training it, and writes one immutable artifact per arm. Eight new fits
in total, which is exactly what section 5 authorises and no more.

Submit through scripts/spawn_modal_jobs.py so the run is server-side; a
detached local run is not a registered execution.

What differs from Stage 0's launcher
------------------------------------
Stage 0 trained nothing and refused to hold an accelerator. Stage 1 trains, so
the GPU refusal is INVERTED rather than inherited: this launcher refuses a
record that authorises no GPU, because a training phase priced without one has
not been priced.

The other difference is that a Stage-1 job's numbers only mean something if the
container scored what M2B scored. The runner enforces three identities and
refuses on each, but it can only check an expectation it is given, so the
expectations are computed HERE, host-side, from M2B's own filed headline
artifacts, and passed in. A job launched without them would still run and would
still produce artifacts; they would simply be uncomparable with the rows the
gate reads. So they are required, per cell, and their absence is a refusal at
submit time rather than a footnote in a result.

The container shape is not decided here. It is read from the compute record
filed before this launcher was allowed to run -- generated by
scripts/m2d_stage1_compute_record.py -- so a job cannot quietly acquire a
larger box than the filed prediction priced, and the spend gate in
spawn_modal_jobs.py prices the shape the container will actually hold.

The declared cells, the arms, the seed and the authorisation all come from
configs/m2d_s4_semantic_repair.yaml. This file restates none of them: a
launcher holding its own copy of the matrix can only ever disagree with the
thing that declared it.
"""

