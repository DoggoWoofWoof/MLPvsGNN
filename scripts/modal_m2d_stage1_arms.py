def compute_record() -> dict[str, Any]:
    """The filed Stage-1 compute record. Host-side only, and read on demand.

    On demand rather than at import because this module is imported inside the
    container too -- Modal loads it there to find ``run_stage1`` -- and the
    image carries no ``outputs/`` tree, so an import-time read would make every
    remote job die at startup. It is also read on demand so the module stays
    importable on a fresh clone, where the record has not been generated yet:
    the registry test imports every launcher, and a launcher that cannot be
    imported without a gitignored artifact is a launcher nobody can check.

    Absence is still refused at the moment it matters, in
    ``require_authorisation``, which is where a launch is actually decided.
    """

    if not COMPUTE_RECORD_PATH.is_file():
        raise SystemExit(
            f"{COMPUTE_RECORD_PATH} does not exist. A filed compute record is a "
            "precondition of this launch; regenerate it with "
            "scripts/m2d_stage1_compute_record.py before submitting."
        )
    record = json.loads(COMPUTE_RECORD_PATH.read_text(encoding="utf-8"))
    if not record.get("filed_before_any_job_was_submitted"):
        raise SystemExit(f"{COMPUTE_RECORD_PATH} is not a pre-launch record")
    # Inverted from Stage 0, which refused to hold an accelerator. Stage 1
    # trains; a record that authorises none has priced something else.
    if record["container"]["gpu"] is None or record.get("authorises_no_gpu"):
        raise SystemExit(
            "the filed record authorises no GPU, but Stage 1 fits eight models. "
            "Regenerate it rather than launching against a prediction for a "
            "different kind of job."
        )
    if record.get("trains_nothing"):
        raise SystemExit("the filed record says this stage trains nothing; it fits 8 models")
    container = record["container"]
    declared = (GPU, CPU, MEMORY_MB, TIMEOUT_SECONDS)
    filed = (
        container["gpu"],
        int(container["cpu_cores"]),
        int(container["memory_mb"]),
        int(container["timeout_seconds"]),
    )
    if declared != filed:
        raise SystemExit(
            f"the declaration's container shape {declared} and the filed record's "
            f"{filed} disagree. They are written by one script; regenerate rather "
            "than reconcile them by hand."
        )
    priced = {item["cell"] for item in record["workload"]["cells"]}
    declared_cells = {f"{dataset}/{regime}" for dataset, regime in CELLS.items()}
    if priced != declared_cells:
        raise SystemExit(
            f"the filed record prices {sorted(priced)} and the declaration names "
            f"{sorted(declared_cells)}. A job nobody priced is a job nobody authorised."
        )
    if int(record["workload"]["fits"]) != len(declared_cells) * len(ARMS):
        raise SystemExit(
            f"the filed record prices {record['workload']['fits']} fits and this "
            f"launcher spawns {len(declared_cells)} cells x {len(ARMS)} arms"
        )
    return record


def _host_commit() -> str | None:
    try:
        return subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=str(HOST_REPO_ROOT),
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()
    except (subprocess.CalledProcessError, FileNotFoundError, OSError):  # pragma: no cover
        return None


def _validation_split_queries(dataset: str, confirmation: dict[str, Any]) -> int:
    """This dataset's validation split size, derived then cross-checked.

    The same derivation M2, M2B, M2C and Stage 0 used, and for the same reason:
    Stage 1 loads M2's sealed cell master under its build key, so it has to ask
    for the identical panel M2 scored. A different number here fails that
    check, which is the correct outcome but a wasteful way to find a
    transcription error.
    """

    measured = int(confirmation["data"]["splits"]["validation"])
    declared = M1A_CONFIG["datasets"].get(dataset, {}).get("validation_split_queries")
    if declared is not None and int(declared) != measured:
        raise ValueError(
            f"{dataset}: configs/m1a_feature_screen.yaml declares validation_split_queries="
            f"{declared} but its confirmation artifact's validation split holds {measured} "
            "queries -- resolve this before launching; Stage 1 reads M2's cell master for "
            "that split and cannot rebuild it"
        )
    return measured


def panel_digest(query_ids: list[str]) -> str:
    """The runner's digest, imported rather than reimplemented.

    Two spellings of one hash is a bug that only ever shows up as an identity
    mismatch on a paid container, which is exactly the failure the identity
    check exists to prevent.
    """

    for path in (HOST_REPO_ROOT, HOST_REPO_ROOT / "src"):
        if str(path) not in sys.path:
            sys.path.insert(0, str(path))
    from scripts.run_m2d_stage1_arms import panel_digest as digest

    return digest(query_ids)


def _s4_seed_spread_pp(dataset: str, regime: str) -> tuple[float, str]:
    """The bound the native-S4 re-score must reproduce M2B's recall@5 within.

    Derived, never typed, and derived twice over because the table does not
    offer the same evidence for every cell.

    Where a cell has more than one filed seed -- the two blockers do -- the
    bound is that cell's OWN measured seed-to-seed spread, which is the gate's
    resolvable band and the most local statement available about how much this
    number moves when nothing meaningful changes.

    Where a cell has one seed -- both controls -- there is no per-cell
    measurement, so the bound is the largest S4 seed spread measured ANYWHERE
    in the filed table. That is looser, and it is labelled as looser in the job
    record rather than presented as the same kind of number.

    The check is deliberately generous either way. Its job is to catch a wrong
    panel, a wrong store or a wrong checkpoint, not to certify float
    reproducibility across devices; the panel digest and the shared-inputs hash
    are the tight checks, and they run first.
    """

    table = json.loads(BASELINE_TABLE.read_text(encoding="utf-8"))
    per_cell: dict[tuple[str, str], list[float]] = {}
    for row in table["rows"]:
        if row["rung"] != NATIVE_RUNG:
            continue
        per_cell.setdefault((row["dataset"], row["regime"]), []).append(row["recall@5"])

    values = per_cell.get((dataset, regime))
    if not values:
        raise ValueError(f"{dataset}/{regime} has no filed {NATIVE_RUNG} row to reproduce")
    if len(values) > 1:
        return (max(values) - min(values)) * 100.0, (
            f"this cell's own measured {NATIVE_RUNG} seed spread across "
            f"{len(values)} filed seeds"
        )
    spreads = [
        (max(seeds) - min(seeds)) * 100.0 for seeds in per_cell.values() if len(seeds) > 1
    ]
    if not spreads:
        raise ValueError(
            "no cell in the filed table has two seeds of "
            f"{NATIVE_RUNG}, so no reproduction bound can be derived from it"
        )
    return max(spreads), (
        f"this cell has one filed seed, so the bound is the largest {NATIVE_RUNG} seed "
        "spread measured anywhere in the table -- looser than a per-cell band, and "
        "labelled as such"
    )


def m2b_expectations(dataset: str, regime: str) -> dict[str, Any]:
    """What this container must reproduce, from M2B's own filed headline.

    Computed host-side and passed in, rather than looked up in the container,
    for two reasons. The volume holds M2B's fits but not its headline JSON, and
    more importantly an expectation the container derives for itself is an
    expectation the container can derive wrongly and then satisfy.
    """

    path = M2B_HEADLINE / f"{dataset}.json"
    if not path.is_file():
        raise FileNotFoundError(
            f"{path} does not exist, so there is nothing for {dataset}/{regime} to be "
            "compared against. Every Stage-1 delta is taken against M2B's filed rows; "
            "a cell whose filed row cannot be read cannot be launched."
        )
    payload = json.loads(path.read_text(encoding="utf-8"))
    block = payload["cells"][regime]
    rung = block["rungs"][NATIVE_RUNG]
    if int(rung["seed"]) != SEED:
        raise ValueError(
            f"{dataset}/{regime}: the filed {NATIVE_RUNG} row is seed {rung['seed']}, "
            f"and Stage 1 runs seed {SEED}"
        )
    bound_pp, bound_source = _s4_seed_spread_pp(dataset, regime)
    return {
        "panel_sha256": panel_digest(list(block["held_out_query_ids"])),
        "shared_inputs_sha256": block["shared_inputs"]["sha256"],
        "s4_recall_at_5": float(rung["metrics"]["recall@5"]),
        "s4_reproduction_bound_pp": bound_pp,
        "s4_reproduction_bound_source": bound_source,
        "held_out_queries": int(block["held_out_queries"]),
        "precomputed_width": int(block["precomputed_width"]),
        "filed_by": str(path.relative_to(HOST_REPO_ROOT)).replace("\\", "/"),
    }


def _m2_fits_root(dataset: str, fingerprint: str) -> PurePosixPath:
    """Where M2's headline run left this dataset's cell masters. Read-only.

    Masters live at ``<root>/<regime>/cell_features``, the layout
    run_m2_qls_v2_freeze.py wrote.
    """

    return (
        PurePosixPath(STORAGE_ROOT)
        / "outputs"
        / M2_OUTPUT_PREFIX
        / dataset
        / fingerprint[:16]
        / MODAL_CONFIG["execution_label"]
        / "headline"
        / "fits"
    )


def _m2b_fits_root(dataset: str, fingerprint: str) -> PurePosixPath:
    """Where M2B left this dataset's semantic checkpoints. Read-only.

    Checkpoints live at ``<root>/<regime>/<rung.lower()>/checkpoint.pt``, the
    layout run_m2b_semantic_minimality.py wrote -- lowercased, which is why the
    rung is not spelled here as the declaration spells it.
    """

    return (
        PurePosixPath(STORAGE_ROOT)
        / "outputs"
        / M2B_OUTPUT_PREFIX
        / dataset
        / fingerprint[:16]
        / MODAL_CONFIG["execution_label"]
        / "headline"
        / "fits"
    )


def _jobs(datasets: list[str]) -> list[dict[str, Any]]:
    unknown = set(datasets) - set(CELLS)
    if unknown:
        raise ValueError(
            f"{sorted(unknown)} are not M2D Stage-1 cells; the declaration names "
            f"{sorted(CELLS)} and no others"
        )
    commit = _host_commit()
    jobs = []
    for dataset in datasets:
        regime = CELLS[dataset]
        settings = CONFIRMATION_CONFIG["datasets"][dataset]
        confirmation_path = HOST_REPO_ROOT / f"outputs/sa_mlp_confirmation/{dataset}.json"
        confirmation = json.loads(confirmation_path.read_text(encoding="utf-8"))
        if confirmation.get("status") != "SA_MLP_CONFIRMATION_DATASET_COMPLETE":
            raise ValueError(f"{confirmation_path} is not a complete confirmation artifact")
        fingerprint = confirmation["data_fingerprint_sha256"]
        jobs.append(
            {
                "dataset": dataset,
                "regime": regime,
                "fingerprint": fingerprint,
                "data_remote": confirmation["config"]["data"],
                "baseline": confirmation["baseline"],
                "expected_queries": int(confirmation["config"]["expected_queries"]),
                # M1A's declared frozen width, read the way M2B's own launcher
                # reads it. Not from the confirmation artifact, which does not
                # carry it, and not typed: every parameter count in section 11
                # is a function of this number.
                "frozen_embedding_dim": int(
                    M1A_CONFIG["base"]["semantic_rung"]["frozen_embedding_dim"]
                ),
                "validation_split_queries": _validation_split_queries(dataset, confirmation),
                "candidate_contract_compatibility": settings.get(
                    "candidate_contract_compatibility"
                ),
                "m2_fits_remote": str(_m2_fits_root(dataset, fingerprint)),
                "m2b_fits_remote": str(_m2b_fits_root(dataset, fingerprint)),
                "expects": m2b_expectations(dataset, regime),
                "arms": list(ARMS),
                "seed": SEED,
                "config_fingerprint": CONFIG_FINGERPRINT,
                "source_commit": commit,
            }
        )
    return jobs


def _active_modal_profile() -> str | None:
    """The profile this client will actually submit under, or None if unreadable.

    None rather than a guess, and the caller refuses on it: the wrong answer
    here sends a job to the wrong workspace, and a Modal volume lives in
    exactly one workspace.
    """

    from_env = os.environ.get("MODAL_PROFILE")
    if from_env:
        return from_env
    try:
        from modal.config import _profile
    except ImportError:  # pragma: no cover - modal always ships this
        return None
    return _profile or None


def execution_placement() -> dict[str, str]:
    """Which workspace each dataset runs on, from M2's declaration and only there.

    Inheriting is the point here rather than a shortcut. Stage 1 reads M2's cell
    masters and M2B's checkpoints, so a cell can only be fit from the workspace
    whose volume holds them -- the one M2 ran it on. The map moves as workspaces
    reach their spend limits, so a second copy could only ever go stale; M2D
    declares no placement of its own for exactly that reason, and a copy
    appearing there later is refused rather than silently preferred.
    """

    copied = CONFIG.get("launch_authorization", {}).get("execution_placement")
    if copied:
        raise SystemExit(
            "configs/m2d_s4_semantic_repair.yaml has grown its own execution_placement. "
            "The map is declared once, in configs/m2_qls_v2_freeze.yaml, and read at "
            "submit time; delete the copy."
        )
    inherited = M2_CONFIG["launch_authorization"].get("execution_placement")
    if not inherited:
        raise SystemExit(
            "configs/m2_qls_v2_freeze.yaml declares no workspace for these datasets; "
            "a dataset with no declared workspace cannot be submitted to one"
        )
    return dict(inherited)


def check_execution_placement(datasets: list[str]) -> dict[str, Any]:
    """Refuse to submit a dataset under a workspace its sealed artifacts are not on.

    scripts/spawn_modal_jobs.py calls this by name if a launcher defines it, so
    the check runs before the app is deployed and before anything is spawned.
    Stage 1 cannot rebuild a missing cell master or refit a missing checkpoint,
    so a misplaced job fails only after its container has started and been
    billed, having proved nothing.

    It is also where the declaration's gates are checked, because this is the
    only hook the server-side submission path calls before it deploys. A gate
    that only ``main`` consulted would be a gate the declared submission route
    walks straight past.
    """

    require_authorisation()
    placement = execution_placement()
    active = _active_modal_profile()
    if active is None:
        raise SystemExit(
            "cannot read the active Modal profile, so the workspace a job would land "
            "in is unknown. Set MODAL_PROFILE before importing modal."
        )
    undeclared = sorted(set(datasets) - set(placement))
    if undeclared:
        raise SystemExit(
            f"{undeclared} have no declared workspace in "
            "configs/m2_qls_v2_freeze.yaml#launch_authorization.execution_placement"
        )
    misplaced = {
        dataset: placement[dataset] for dataset in datasets if placement[dataset] != active
    }
    if misplaced:
        raise SystemExit(
            f"active profile {active!r} is not where these datasets' sealed artifacts "
            f"live: {misplaced}. Submit each dataset under its declared workspace."
        )
    return {"active_profile": active, "datasets": {d: placement[d] for d in datasets}}


def require_authorisation() -> None:
    """The declaration's gates, checked at call time rather than at import.

    At call time so this module stays importable -- and testable -- whatever the
    gates currently say, which is this track's standing order: commit the
    mechanism before the authorisation.
    """

    authorisation = CONFIG["launch_authorization"]
    gates = authorisation["gates"]
    for gate in (
        "stage_0_advance_gate_evaluated",
        "stage_1_amendment_filed",
        "stage_1_authorised",
        "stage_1_gate_committed",
        "stage_1_compute_record_filed",
    ):
        if not gates.get(gate):
            raise SystemExit(
                f"configs/m2d_s4_semantic_repair.yaml has not earned {gate}. "
                "Every one of these is a precondition of this launch."
            )
    if CONFIG["stage_1"]["seeds"] != [SEED]:
        raise SystemExit(
            f"the declaration now names seeds {CONFIG['stage_1']['seeds']}; this "
            f"launcher spawns seed {SEED} only, and section 15 puts the extra seeds "
            "after the gate rather than beside it"
        )
    forbidden = {item.lower() for item in authorisation["not_authorised"]}
    if "seeds 1 and 2" not in forbidden or "the full 14-cell m2d screen" not in forbidden:
        raise SystemExit(
            "the declaration no longer restricts M2D to the seed-0 cells, so this "
            "launcher can no longer assume the eight fits it spawns are the whole "
            "authorised workload"
        )
    # Last, because it is the expensive one and because its failure message is
    # about regenerating an artifact rather than about authorisation.
    compute_record()


def _output_root(job: dict[str, Any]) -> PurePosixPath:
    """The run store this cell's artifacts are written INTO, not their paths.

    run_artifacts derives the rest -- phase, dataset, regime, arm, commit and
    run id -- so two submissions of the same cell cannot address one file.
    """

    return (
        PurePosixPath(STORAGE_ROOT)
        / "outputs"
        / OUTPUT_PREFIX
        / STAGE_PREFIX
        / job["dataset"]
        / job["fingerprint"][:16]
        / MODAL_CONFIG["execution_label"]
    )


