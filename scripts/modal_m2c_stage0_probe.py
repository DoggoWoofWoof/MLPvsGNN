#: The four declared cells, read from the declaration. One dataset each, which
#: is what lets a job be addressed by dataset the way every other launcher in
#: this track is; a fifth cell on an already-listed dataset would break that,
#: and is refused here rather than discovered as an overwritten result.
_CELL_BLOCK = CONFIG["stage_0"]["cells"]
CELLS: dict[str, str] = {}
for _cell in (
    *_CELL_BLOCK["failure_cells"],
    _CELL_BLOCK["passage_r3_control"],
    _CELL_BLOCK["kb_r3_control"],
):
    _dataset, _regime = _cell.split("/")
    if _dataset in CELLS:
        raise RuntimeError(
            f"{_dataset} carries two declared Stage-0 cells; this launcher spawns one "
            "job per dataset and the second would overwrite the first"
        )
    CELLS[_dataset] = _regime

# spawn_modal_jobs.py's shared package protocol validates --datasets against
# module.CONFIG["datasets"]. The alias satisfies that contract without adding a
# datasets key to the declaration's own schema.
CONFIG["datasets"] = CELLS

#: The container shape the compute record filed, taken from the declaration's
#: own copy of it. The generated record and this block are written by the same
#: script and a declaration test holds them equal; this is the copy that is
#: committed, and -- decisively -- the copy that exists inside the container,
#: because the image carries src/, scripts/ and configs/ and no outputs/ tree.
#: The decorator below is evaluated remotely as well as locally, so it can only
#: read from something the container has.
SHAPE = CONFIG["launch_authorization"]["stage_0_compute_record"]
if SHAPE["gpu"] is not None or SHAPE["gpu_hours_authorised"]:
    raise RuntimeError("M2C Stage 0 authorises zero GPU hours; refusing to hold one")

# Copied, not aliased: M2C must not be able to change M1A's or M2's infra view.
# The infra keys -- volume, storage root, execution label, provenance root --
# stay M1A's, because they name where the frozen artifacts actually are. The
# SHAPE keys are overwritten from the filed record, because M1A's are a training
# phase's (A10G, 16 cores, 48 GiB, 24 h) and pricing this probe at them would
# report a threefold spend against a declaration it never breached.
MODAL_CONFIG = dict(M1A_CONFIG["modal"])
GPU = SHAPE["gpu"]
CPU = int(SHAPE["cpu"])
MEMORY_MB = int(SHAPE["memory_mb"])
TIMEOUT_SECONDS = int(SHAPE["timeout_seconds"])
MODAL_CONFIG.update(
    {"gpu": GPU, "cpu": CPU, "memory_mb": MEMORY_MB, "timeout_seconds": TIMEOUT_SECONDS}
)

STORAGE_ROOT = MODAL_CONFIG["storage_root"]
APP_NAME = "message-passing-retrieval-m2c-stage0-probe"
OUTPUT_PREFIX = "m2c_s4_structural_conditioning"
M2_OUTPUT_PREFIX = "m2_qls_v2_freeze"
M2B_OUTPUT_PREFIX = "m2b_semantic_minimality"

#: The rung whose weights Stage 0 reads, and the directory M2B stored it in.
#: M2B writes ``fit_root = cell_root / rung.lower()``, so the two differ in
#: case; on the container's filesystem that difference is a missing file.
S4_RUNG = "S4"
S4_FIT_DIRECTORY = S4_RUNG.lower()

#: One cell is one spawned call that writes its result once, at the end. A
#: restart therefore redoes exactly one cell and no more, and a re-spawn of a
#: finished cell returns its recorded result without recomputing it.
#: spawn_modal_jobs.py reads this to decide whether the piece a restart redoes
#: is one job or the whole probe; silence there is costed as no resumption.
RESUME_GRANULARITY = "cell"

app = modal.App(APP_NAME)
